// @ts-check
const fs = require('node:fs');
const path = require('node:path');
const { withDangerousMod } = require('expo/config-plugins');

/**
 * Lets R8 minify the release APK with org.jitsi:webrtc 155 (react-native-webrtc 155).
 *
 * That AAR ships org/webrtc/Dav1dDecoderJni.class without the Dav1dDecoder class or the
 * Dav1dDecoder.Natives interface the stub implements (LibvpxVp8Decoder, next to it, has all
 * three). react-native-webrtc's consumer rules keep every org.webrtc class, so R8 keeps the stub,
 * cannot resolve its interface and stops the build. Nothing can reach the stub without
 * Dav1dDecoder, which is not there, and the app's decoders are the software and H.264 ones, so
 * leaving the interface missing changes nothing at runtime.
 *
 * android/ is generated by `expo prebuild` and not committed, so the rule is added here.
 */
const RULES = [
  '# org.jitsi:webrtc 155 ships Dav1dDecoderJni without the interface it implements (see',
  '# plugins/withWebrtcProguard.cjs).',
  '-dontwarn org.webrtc.Dav1dDecoder$Natives',
];

/** @type {import('expo/config-plugins').ConfigPlugin} */
const withWebrtcProguard = (config) =>
  withDangerousMod(config, [
    'android',
    (config) => {
      const file = path.join(config.modRequest.platformProjectRoot, 'app', 'proguard-rules.pro');
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      if (!current.includes(RULES[RULES.length - 1])) {
        const separator = current === '' || current.endsWith('\n') ? '' : '\n';
        fs.writeFileSync(file, `${current}${separator}\n${RULES.join('\n')}\n`);
      }
      return config;
    },
  ]);

module.exports = withWebrtcProguard;
