/** The MCP server name agents see. Underscores, so Codex's TOML keys need no quoting. */
export const AI_ACCESS_MCP_SERVER = 'runova_app';
export const AI_ACCESS_MCP_SCRIPT = 'runova-app-mcp.cjs';

/**
 * The stdio MCP server an agent starts to use Runova (E46). It has no dependencies and holds no
 * tools of its own: the list and every call go to Runova (POST /app-mcp/*), so a Runova update
 * changes what agents can do without touching the script. It passes on what it knows about its
 * session: the Runova tab it runs in and that tab's key, the folder it runs in, the client's name
 * and whether the client can ask the user itself. When Runova wants the user asked in the CLI, the
 * script asks through MCP elicitation and sends the answer back.
 */
export function aiAccessBridgeScriptSource({ portFile }: { portFile: string }): string {
  return String.raw`#!/usr/bin/env node
// Generated by Runova. Lets an AI agent use Runova through MCP, within what the user allows in
// Runova under Settings > AI access. Writes only protocol messages to stdout.
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const http = require('node:http');
const readline = require('node:readline');

const PORT_FILE = ${JSON.stringify(portFile)};
const SESSION_ID = process.env.RUNOVA_SESSION_ID || '';
const SESSION_KEY = process.env.RUNOVA_AI_ACCESS_KEY || '';
const CONNECTION_ID = crypto.randomBytes(16).toString('hex');
const DEFAULT_PROTOCOL_VERSION = '2025-06-18';
// Long enough for the user to answer an approval in the Runova window.
const CALL_TIMEOUT_MS = 5 * 60 * 1000;

let canElicit = false;
let clientName = '';
let nextRequestId = 1;
const waitingOnClient = new Map();

function send(message) {
  process.stdout.write(JSON.stringify(message) + '\n');
}

function textResult(text, isError) {
  return { content: [{ type: 'text', text: text }], isError: Boolean(isError) };
}

function readConnection() {
  try {
    const data = JSON.parse(fs.readFileSync(PORT_FILE, 'utf-8'));
    if (typeof data.port === 'number' && typeof data.token === 'string') return data;
  } catch {}
  return null;
}

function hello() {
  const fields = { connectionId: CONNECTION_ID, cwd: process.cwd(), canElicit: canElicit };
  if (SESSION_ID) fields.sessionId = SESSION_ID;
  if (SESSION_KEY) fields.sessionKey = SESSION_KEY;
  if (clientName) fields.clientName = clientName;
  return fields;
}

function askRunova(path, body) {
  return new Promise((resolve, reject) => {
    const connection = readConnection();
    if (!connection) {
      reject(new Error('Runova is not running. Open Runova and try again.'));
      return;
    }
    const payload = JSON.stringify(Object.assign({ token: connection.token }, body));
    const request = http.request(
      {
        host: '127.0.0.1',
        port: connection.port,
        path: path,
        method: 'POST',
        headers: { 'content-type': 'application/json', 'content-length': Buffer.byteLength(payload) },
        timeout: CALL_TIMEOUT_MS,
      },
      (response) => {
        let data = '';
        response.setEncoding('utf-8');
        response.on('data', (chunk) => {
          data += chunk;
        });
        response.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch {
            reject(new Error('Runova sent an answer this bridge cannot read. Update Runova and try again.'));
          }
        });
      },
    );
    request.on('timeout', () => request.destroy(new Error('Runova did not answer in time.')));
    request.on('error', (error) =>
      reject(
        new Error(
          error.code === 'ECONNREFUSED' ? 'Runova is not running. Open Runova and try again.' : error.message,
        ),
      ),
    );
    request.end(payload);
  });
}

/** Sends the client a request of our own and waits for its answer. */
function askClient(method, params) {
  const id = 'runova-' + nextRequestId++;
  return new Promise((resolve) => {
    waitingOnClient.set(id, resolve);
    send({ jsonrpc: '2.0', id: id, method: method, params: params });
  });
}

async function askUser(confirm) {
  const reply = await askClient('elicitation/create', {
    message: confirm.message,
    requestedSchema: {
      type: 'object',
      properties: {
        remember: {
          type: 'boolean',
          title: 'Allow for the rest of this session',
          description: 'Runova will not ask again for this tool until the agent restarts.',
          default: false,
        },
      },
    },
  });
  const result = reply && reply.result;
  if (!result || result.action !== 'accept') return 'deny';
  return result.content && result.content.remember === true ? 'allow_session' : 'allow';
}

function toResult(answer) {
  if (!answer || !answer.ok) return textResult((answer && answer.error) || 'Runova refused the request.', true);
  if (answer.data !== undefined) return textResult(JSON.stringify(answer.data, null, 2), false);
  return textResult(typeof answer.text === 'string' ? answer.text : 'Done.', false);
}

async function callTool(name, args) {
  const answer = await askRunova(
    '/app-mcp/call',
    Object.assign(hello(), { tool: String(name), args: args && typeof args === 'object' ? args : {} }),
  );
  if (answer && answer.ok && answer.confirm) {
    const decision = await askUser(answer.confirm);
    return toResult(
      await askRunova('/app-mcp/decide', {
        connectionId: CONNECTION_ID,
        approvalId: answer.confirm.approvalId,
        decision: decision,
      }),
    );
  }
  return toResult(answer);
}

async function handle(message) {
  if (!message || typeof message !== 'object') return;
  // An answer to a request this script sent the client.
  if (message.method === undefined && message.id !== undefined && waitingOnClient.has(message.id)) {
    const resolve = waitingOnClient.get(message.id);
    waitingOnClient.delete(message.id);
    resolve(message);
    return;
  }
  if (message.id === undefined || message.id === null) return;
  const id = message.id;
  const params = message.params || {};
  if (message.method === 'initialize') {
    const capabilities = params.capabilities || {};
    canElicit = Boolean(capabilities.elicitation);
    clientName = params.clientInfo && typeof params.clientInfo.name === 'string' ? params.clientInfo.name : '';
    const version =
      typeof params.protocolVersion === 'string' ? params.protocolVersion : DEFAULT_PROTOCOL_VERSION;
    send({
      jsonrpc: '2.0',
      id,
      result: {
        protocolVersion: version,
        capabilities: { tools: {} },
        serverInfo: { name: 'runova_app', title: 'Runova', version: '1.0.0' },
        instructions:
          'Runova manages this user\'s projects, environment files, API Client collections and more. Use these tools to read or change them instead of editing Runova\'s files. What runs without asking depends on the user\'s settings in Runova.',
      },
    });
    return;
  }
  if (message.method === 'ping') {
    send({ jsonrpc: '2.0', id, result: {} });
    return;
  }
  if (message.method === 'tools/list') {
    try {
      const answer = await askRunova('/app-mcp/tools', hello());
      if (!answer || !answer.ok) throw new Error((answer && answer.error) || 'Runova refused the request.');
      send({ jsonrpc: '2.0', id, result: { tools: answer.tools } });
    } catch (error) {
      send({ jsonrpc: '2.0', id, error: { code: -32603, message: error instanceof Error ? error.message : 'Something went wrong.' } });
    }
    return;
  }
  if (message.method === 'tools/call') {
    let result;
    try {
      result = await callTool(params.name, params.arguments);
    } catch (error) {
      result = textResult(error instanceof Error ? error.message : 'Something went wrong.', true);
    }
    send({ jsonrpc: '2.0', id, result });
    return;
  }
  send({ jsonrpc: '2.0', id, error: { code: -32601, message: 'Method not found: ' + String(message.method) } });
}

let inFlight = 0;
let inputClosed = false;

function exitWhenIdle() {
  if (inputClosed && inFlight === 0) process.exit(0);
}

const lines = readline.createInterface({ input: process.stdin, terminal: false });
lines.on('line', (line) => {
  if (line.trim() === '') return;
  let message;
  try {
    message = JSON.parse(line);
  } catch {
    send({ jsonrpc: '2.0', id: null, error: { code: -32700, message: 'Parse error' } });
    return;
  }
  inFlight += 1;
  handle(message)
    .catch(() => {})
    .finally(() => {
      inFlight -= 1;
      exitWhenIdle();
    });
});
lines.on('close', () => {
  inputClosed = true;
  // Nobody is left to answer, so whatever was being asked counts as a no.
  for (const resolve of waitingOnClient.values()) resolve(null);
  waitingOnClient.clear();
  exitWhenIdle();
});
`;
}
