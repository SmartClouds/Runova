import { type DbObjectRef, qualifiedName, quoteIdentifier, quoteLiteral } from './sqlBuild.js';
import type { DbEngine } from './types.js';

/**
 * SQL for the table designer and the grid's row edits. Everything here is shown to the user
 * before it runs, so it is written plainly, one statement per line, with every name quoted.
 */

export interface ColumnDraft {
  name: string;
  type: string;
  nullable: boolean;
  primaryKey: boolean;
  autoIncrement?: boolean;
  unique?: boolean;
  /** An SQL expression, as typed: 'guest', 0, now(). */
  defaultValue?: string | null;
  /** In an edit of an existing table: the column's name before, or nothing for a new column. */
  originalName?: string;
}

export interface TableDraft {
  ref: DbObjectRef;
  columns: ColumnDraft[];
}

export type RowEdit =
  | { kind: 'update'; key: Record<string, unknown>; values: Record<string, unknown> }
  | { kind: 'insert'; values: Record<string, unknown> }
  | { kind: 'delete'; key: Record<string, unknown> };

/** Letters, digits and the punctuation types use: varchar(255), numeric(10,2), map<text, int>. */
const TYPE = /^[A-Za-z][\w ,()<>[\].']*$/;

function checkType(type: string): string {
  const trimmed = type.trim();
  const depth = [...trimmed].reduce((open, ch) => open + (ch === '(' ? 1 : ch === ')' ? -1 : 0), 0);
  if (!TYPE.test(trimmed) || trimmed.includes('--') || depth !== 0) {
    throw new Error(`"${type}" is not a column type.`);
  }
  return trimmed;
}

function checkExpression(value: string): string {
  if (value.includes(';') || value.includes('--') || value.includes('/*')) {
    throw new Error(`The default "${value}" must be one value, like 0, 'text' or now().`);
  }
  return value.trim();
}

function checkColumns(columns: readonly ColumnDraft[], allowEmpty = false): void {
  if (columns.length === 0 && !allowEmpty) throw new Error('A table needs at least one column.');
  const seen = new Set<string>();
  for (const column of columns) {
    if (!column.name.trim()) throw new Error('Every column needs a name.');
    const key = column.name.trim().toLowerCase();
    if (seen.has(key)) throw new Error(`The column ${column.name} is there twice.`);
    seen.add(key);
  }
}

const SQL_ENGINES = new Set<DbEngine>([
  'postgres',
  'mysql',
  'mariadb',
  'sqlite',
  'mssql',
  'cassandra',
]);

/** One column as it is written inside CREATE TABLE (and MySQL's MODIFY COLUMN). */
function columnDefinition(engine: DbEngine, column: ColumnDraft, inlineKey: boolean): string {
  const name = quoteIdentifier(engine, column.name.trim());
  const type = checkType(column.type);
  if (engine === 'cassandra') return `${name} ${type}`;
  if (inlineKey) return `${name} INTEGER PRIMARY KEY AUTOINCREMENT`;
  const parts = [name, type];
  if (column.autoIncrement) {
    if (engine === 'postgres') parts.push('GENERATED BY DEFAULT AS IDENTITY');
    if (engine === 'mssql') parts.push('IDENTITY(1,1)');
  }
  if (!column.nullable) parts.push('NOT NULL');
  if (column.autoIncrement && (engine === 'mysql' || engine === 'mariadb'))
    parts.push('AUTO_INCREMENT');
  if (column.defaultValue?.trim() && !column.autoIncrement) {
    parts.push(`DEFAULT ${checkExpression(column.defaultValue)}`);
  }
  if (column.unique && !column.primaryKey) parts.push('UNIQUE');
  return parts.join(' ');
}

/** A Mongo field type as the validator writes it. */
function bsonType(column: ColumnDraft): string | string[] {
  const type = column.type.trim() || 'string';
  return column.nullable ? [type, 'null'] : type;
}

export function buildCreateTable(engine: DbEngine, draft: TableDraft): string {
  if (engine === 'mongodb') {
    checkColumns(draft.columns, true);
    const name = JSON.stringify(draft.ref.name);
    if (draft.columns.length === 0) return `db.createCollection(${name})`;
    const required = draft.columns
      .filter((column) => !column.nullable)
      .map((column) => column.name);
    const schema: Record<string, unknown> = { bsonType: 'object' };
    if (required.length > 0) schema.required = required;
    schema.properties = Object.fromEntries(
      draft.columns.map((column) => [column.name, { bsonType: bsonType(column) }]),
    );
    return `db.createCollection(${name}, ${JSON.stringify({ validator: { $jsonSchema: schema } })})`;
  }
  if (!SQL_ENGINES.has(engine)) throw new Error(`${engine} has no tables to design.`);
  checkColumns(draft.columns);
  const keys = draft.columns.filter((column) => column.primaryKey);
  if (engine === 'cassandra' && keys.length === 0) {
    throw new Error('A Cassandra table needs a primary key.');
  }
  const inlineKey =
    engine === 'sqlite' && keys.length === 1 && keys[0]?.autoIncrement === true ? keys[0] : null;
  const lines = draft.columns.map((column) =>
    columnDefinition(engine, column, column === inlineKey),
  );
  if (keys.length > 0 && !inlineKey) {
    lines.push(
      `PRIMARY KEY (${keys.map((column) => quoteIdentifier(engine, column.name.trim())).join(', ')})`,
    );
  }
  return `CREATE TABLE ${qualifiedName(engine, draft.ref)} (\n${lines.map((line) => `  ${line}`).join(',\n')}\n);`;
}

function sameType(a: string, b: string): boolean {
  return (
    a.trim().toLowerCase().replace(/\s+/g, ' ') === b.trim().toLowerCase().replace(/\s+/g, ' ')
  );
}

function sameDefault(a: string | null | undefined, b: string | null | undefined): boolean {
  return (a?.trim() || null) === (b?.trim() || null);
}

/** The statements that turn the columns `before` into `after`: drops, renames, changes, adds. */
export function buildAlterTable(
  engine: DbEngine,
  ref: DbObjectRef,
  before: readonly ColumnDraft[],
  after: readonly ColumnDraft[],
): string[] {
  checkColumns(after);
  const table = `ALTER TABLE ${qualifiedName(engine, ref)}`;
  const q = (name: string) => quoteIdentifier(engine, name.trim());
  const kept = new Set(after.map((column) => column.originalName).filter(Boolean));
  const drops: string[] = [];
  const renames: string[] = [];
  const changes: string[] = [];
  const adds: string[] = [];

  for (const column of before) {
    if (!kept.has(column.name)) drops.push(`${table} DROP COLUMN ${q(column.name)};`);
  }
  for (const column of after) {
    const original = column.originalName
      ? before.find((one) => one.name === column.originalName)
      : undefined;
    if (!original) {
      const keyword = engine === 'mssql' || engine === 'cassandra' ? 'ADD' : 'ADD COLUMN';
      adds.push(
        `${table} ${keyword} ${columnDefinition(engine, { ...column, primaryKey: false }, false)};`,
      );
      continue;
    }
    const renamed = column.name.trim() !== original.name;
    if (renamed) {
      renames.push(
        engine === 'mssql'
          ? `EXEC sp_rename ${quoteLiteral(engine, `${qualifiedName(engine, ref)}.${q(original.name)}`)}, ${quoteLiteral(engine, column.name.trim())}, 'COLUMN';`
          : `${table} RENAME COLUMN ${q(original.name)} TO ${q(column.name)};`,
      );
    }
    const typeChanged = !sameType(original.type, column.type);
    const nullChanged = original.nullable !== column.nullable;
    const defaultChanged = !sameDefault(original.defaultValue, column.defaultValue);
    if (!typeChanged && !nullChanged && !defaultChanged) continue;
    const name = q(column.name);
    switch (engine) {
      case 'postgres':
        if (typeChanged)
          changes.push(`${table} ALTER COLUMN ${name} TYPE ${checkType(column.type)};`);
        if (nullChanged) {
          changes.push(
            `${table} ALTER COLUMN ${name} ${column.nullable ? 'DROP' : 'SET'} NOT NULL;`,
          );
        }
        if (defaultChanged) {
          changes.push(
            column.defaultValue?.trim()
              ? `${table} ALTER COLUMN ${name} SET DEFAULT ${checkExpression(column.defaultValue)};`
              : `${table} ALTER COLUMN ${name} DROP DEFAULT;`,
          );
        }
        break;
      case 'mysql':
      case 'mariadb':
        changes.push(
          `${table} MODIFY COLUMN ${columnDefinition(engine, { ...column, primaryKey: false }, false)};`,
        );
        break;
      case 'mssql':
        if (typeChanged || nullChanged) {
          changes.push(
            `${table} ALTER COLUMN ${name} ${checkType(column.type)}${column.nullable ? ' NULL' : ' NOT NULL'};`,
          );
        }
        if (defaultChanged) {
          throw new Error(
            'SQL Server keeps defaults as named constraints; change it with a query.',
          );
        }
        break;
      default:
        throw new Error(
          `${engine === 'sqlite' ? 'SQLite' : 'Cassandra'} cannot change a column's type, null rule or default. Make a new column instead.`,
        );
    }
  }
  return [...drops, ...renames, ...changes, ...adds];
}

export function buildDropTable(engine: DbEngine, ref: DbObjectRef): string {
  if (engine === 'mongodb') return `db.getCollection(${JSON.stringify(ref.name)}).drop()`;
  return `DROP TABLE ${qualifiedName(engine, ref)};`;
}

const NUMERIC_TYPE =
  /^(tiny|small|medium|big)?int|^integer|serial|^numeric|^decimal|^real|^double|^float|^number|^money|^bit\b|^counter|^varint|^smallmoney/i;
const NUMBER = /^-?\d+(\.\d+)?(e[+-]?\d+)?$/i;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** A value from the grid as an SQL literal for its column. */
export function sqlLiteral(engine: DbEngine, value: unknown, columnType: string | null): string {
  if (value === null || value === undefined) return 'NULL';
  const type = columnType?.trim() ?? '';
  if (/^bool/i.test(type)) {
    const text = String(value).toLowerCase();
    if (text === 'true' || text === '1' || text === 't') return 'TRUE';
    if (text === 'false' || text === '0' || text === 'f') return 'FALSE';
  }
  if (NUMERIC_TYPE.test(type)) {
    const text = String(value).trim();
    if (NUMBER.test(text)) return text;
  }
  if (engine === 'cassandra' && /uuid$/i.test(type) && UUID.test(String(value)))
    return String(value);
  const text = typeof value === 'object' ? JSON.stringify(value) : String(value);
  return quoteLiteral(engine, text);
}

const TRANSACTION: Partial<Record<DbEngine, [string, string]>> = {
  postgres: ['BEGIN;', 'COMMIT;'],
  sqlite: ['BEGIN;', 'COMMIT;'],
  mysql: ['START TRANSACTION;', 'COMMIT;'],
  mariadb: ['START TRANSACTION;', 'COMMIT;'],
  mssql: ['BEGIN TRANSACTION;', 'COMMIT;'],
};

/**
 * The grid's pending edits as statements in one transaction, so they all land or none do. Every
 * update and delete names its row by key; an edit with no key is refused rather than allowed to
 * reach every row.
 */
export function buildRowEdits(
  engine: DbEngine,
  ref: DbObjectRef,
  columns: readonly { name: string; type: string | null }[],
  edits: readonly RowEdit[],
): string {
  if (edits.length === 0) return '';
  const table = qualifiedName(engine, ref);
  const typeOf = new Map(columns.map((column) => [column.name, column.type]));
  const q = (name: string) => quoteIdentifier(engine, name);
  const literal = (name: string, value: unknown) =>
    sqlLiteral(engine, value, typeOf.get(name) ?? null);
  const where = (key: Record<string, unknown>) => {
    const entries = Object.entries(key);
    if (entries.length === 0) throw new Error('A row edit needs the key that picks out its row.');
    return entries
      .map(([name, value]) =>
        value === null ? `${q(name)} IS NULL` : `${q(name)} = ${literal(name, value)}`,
      )
      .join(' AND ');
  };
  const statements = edits.map((edit) => {
    switch (edit.kind) {
      case 'update': {
        const sets = Object.entries(edit.values).map(
          ([name, value]) => `${q(name)} = ${literal(name, value)}`,
        );
        return `UPDATE ${table} SET ${sets.join(', ')} WHERE ${where(edit.key)};`;
      }
      case 'insert': {
        const names = Object.keys(edit.values);
        return `INSERT INTO ${table} (${names.map(q).join(', ')}) VALUES (${names.map((name) => literal(name, edit.values[name])).join(', ')});`;
      }
      case 'delete':
        return `DELETE FROM ${table} WHERE ${where(edit.key)};`;
    }
  });
  const wrap = TRANSACTION[engine];
  return (wrap ? [wrap[0], ...statements, wrap[1]] : statements).join('\n');
}

