import { describe, expect, it } from 'vitest';
import {
  buildAlterTable,
  buildCreateTable,
  buildDropTable,
  buildRowEdits,
  columnTypeSuggestions,
  sqlLiteral,
  type TableDraft,
} from './ddl.js';

/**
 * The table designer and the grid's row edits turn what the user clicked into SQL, which is shown
 * before it runs. It has to be right for every dialect, and quote every name and value.
 */

const draft = (overrides: Partial<TableDraft> = {}): TableDraft => ({
  ref: { schema: 'public', name: 'orders' },
  columns: [
    { name: 'id', type: 'integer', nullable: false, primaryKey: true, autoIncrement: true },
    { name: 'customer', type: 'text', nullable: false, primaryKey: false, defaultValue: "'guest'" },
    { name: 'total', type: 'numeric(10,2)', nullable: true, primaryKey: false, unique: false },
  ],
  ...overrides,
});

describe('buildCreateTable', () => {
  it('writes a Postgres table with an identity key', () => {
    expect(buildCreateTable('postgres', draft())).toBe(
      [
        'CREATE TABLE "public"."orders" (',
        '  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
        `  "customer" text NOT NULL DEFAULT 'guest',`,
        '  "total" numeric(10,2),',
        '  PRIMARY KEY ("id")',
        ');',
      ].join('\n'),
    );
  });

  it('writes MySQL with AUTO_INCREMENT and backticks', () => {
    expect(
      buildCreateTable('mysql', draft({ ref: { database: 'shop', name: 'orders' } })),
    ).toContain('`id` integer NOT NULL AUTO_INCREMENT');
    expect(buildCreateTable('mysql', draft({ ref: { database: 'shop', name: 'orders' } }))).toMatch(
      /^CREATE TABLE `shop`\.`orders`/,
    );
  });

  it('writes SQL Server with IDENTITY and SQLite with its rowid key', () => {
    expect(buildCreateTable('mssql', draft({ ref: { schema: 'dbo', name: 'orders' } }))).toContain(
      '[id] integer IDENTITY(1,1) NOT NULL',
    );
    const sqlite = buildCreateTable('sqlite', draft({ ref: { name: 'orders' } }));
    expect(sqlite).toContain('"id" INTEGER PRIMARY KEY AUTOINCREMENT');
    expect(sqlite).not.toContain('PRIMARY KEY ("id")');
  });

  it('writes CQL, where a key is required and there are no defaults', () => {
    const cql = buildCreateTable(
      'cassandra',
      draft({
        ref: { database: 'ks', name: 'orders' },
        columns: [
          { name: 'id', type: 'uuid', nullable: false, primaryKey: true },
          { name: 'note', type: 'text', nullable: true, primaryKey: false, defaultValue: "'x'" },
        ],
      }),
    );
    expect(cql).toBe(
      [
        'CREATE TABLE "ks"."orders" (',
        '  "id" uuid,',
        '  "note" text,',
        '  PRIMARY KEY ("id")',
        ');',
      ].join('\n'),
    );
  });

  it('adds UNIQUE where asked and keeps a composite key in order', () => {
    const sql = buildCreateTable(
      'postgres',
      draft({
        columns: [
          { name: 'a', type: 'int', nullable: false, primaryKey: true },
          { name: 'b', type: 'int', nullable: false, primaryKey: true },
          { name: 'c', type: 'text', nullable: true, primaryKey: false, unique: true },
        ],
      }),
    );
    expect(sql).toContain('"c" text UNIQUE');
    expect(sql).toContain('PRIMARY KEY ("a", "b")');
  });

  it('turns down a table it cannot write', () => {
    expect(() => buildCreateTable('postgres', draft({ columns: [] }))).toThrow(
      /at least one column/i,
    );
    expect(() =>
      buildCreateTable(
        'postgres',
        draft({ columns: [{ name: ' ', type: 'int', nullable: true, primaryKey: false }] }),
      ),
    ).toThrow(/name/i);
    expect(() =>
      buildCreateTable(
        'postgres',
        draft({
          columns: [
            { name: 'a', type: 'int', nullable: true, primaryKey: false },
            { name: 'A', type: 'int', nullable: true, primaryKey: false },
          ],
        }),
      ),
    ).toThrow(/twice/i);
    expect(() =>
      buildCreateTable(
        'postgres',
        draft({
          columns: [
            { name: 'a', type: 'int); drop table x; --', nullable: true, primaryKey: false },
          ],
        }),
      ),
    ).toThrow(/type/i);
    expect(() =>
      buildCreateTable(
        'cassandra',
        draft({ columns: [{ name: 'a', type: 'int', nullable: true, primaryKey: false }] }),
      ),
    ).toThrow(/primary key/i);
    expect(() => buildCreateTable('redis', draft())).toThrow(/tables/i);
  });

  it('writes a Mongo collection with a schema validator', () => {
    expect(
      buildCreateTable('mongodb', {
        ref: { database: 'shop', name: 'orders' },
        columns: [
          { name: 'customer', type: 'string', nullable: false, primaryKey: false },
          { name: 'total', type: 'double', nullable: true, primaryKey: false },
        ],
      }),
    ).toBe(
      'db.createCollection("orders", {"validator":{"$jsonSchema":{"bsonType":"object","required":["customer"],"properties":{"customer":{"bsonType":"string"},"total":{"bsonType":["double","null"]}}}}})',
    );
  });
});

describe('buildAlterTable', () => {
  const before = draft().columns;

  it('adds, drops, renames and retypes columns as separate statements', () => {
    const statements = buildAlterTable('postgres', { schema: 'public', name: 'orders' }, before, [
      { ...before[0]!, originalName: 'id' },
      { ...before[1]!, name: 'client', originalName: 'customer' },
      { name: 'paid', type: 'boolean', nullable: false, primaryKey: false, defaultValue: 'false' },
    ]);
    expect(statements).toEqual([
      'ALTER TABLE "public"."orders" DROP COLUMN "total";',
      'ALTER TABLE "public"."orders" RENAME COLUMN "customer" TO "client";',
      'ALTER TABLE "public"."orders" ADD COLUMN "paid" boolean NOT NULL DEFAULT false;',
    ]);
  });

  it('changes a type and nullability in each dialect', () => {
    const changed = [
      { ...before[0]!, originalName: 'id' },
      { ...before[1]!, originalName: 'customer' },
      { ...before[2]!, originalName: 'total', type: 'numeric(12,2)', nullable: false },
    ];
    expect(
      buildAlterTable('postgres', { schema: 'public', name: 'orders' }, before, changed),
    ).toEqual([
      'ALTER TABLE "public"."orders" ALTER COLUMN "total" TYPE numeric(12,2);',
      'ALTER TABLE "public"."orders" ALTER COLUMN "total" SET NOT NULL;',
    ]);
    expect(buildAlterTable('mysql', { database: 'shop', name: 'orders' }, before, changed)).toEqual(
      ['ALTER TABLE `shop`.`orders` MODIFY COLUMN `total` numeric(12,2) NOT NULL;'],
    );
    expect(buildAlterTable('mssql', { schema: 'dbo', name: 'orders' }, before, changed)).toEqual([
      'ALTER TABLE [dbo].[orders] ALTER COLUMN [total] numeric(12,2) NOT NULL;',
    ]);
  });

  it('renames with sp_rename on SQL Server', () => {
    expect(
      buildAlterTable(
        'mssql',
        { schema: 'dbo', name: 't' },
        [before[1]!],
        [{ ...before[1]!, name: 'client', originalName: 'customer' }],
      ),
    ).toEqual(["EXEC sp_rename N'[dbo].[t].[customer]', N'client', 'COLUMN';"]);
  });

  it('sets and drops a Postgres default, and adds a column with each engine keyword', () => {
    const one = [{ name: 'a', type: 'int', nullable: true, primaryKey: false, defaultValue: '1' }];
    expect(
      buildAlterTable('postgres', { name: 't' }, one, [
        { ...one[0]!, originalName: 'a', defaultValue: null },
      ]),
    ).toEqual(['ALTER TABLE "t" ALTER COLUMN "a" DROP DEFAULT;']);
    expect(
      buildAlterTable('postgres', { name: 't' }, one, [
        { ...one[0]!, originalName: 'a', defaultValue: '2' },
      ]),
    ).toEqual(['ALTER TABLE "t" ALTER COLUMN "a" SET DEFAULT 2;']);
    const added = [
      { ...one[0]!, originalName: 'a' },
      { name: 'b', type: 'text', nullable: true, primaryKey: false },
    ];
    expect(buildAlterTable('mssql', { schema: 'dbo', name: 't' }, one, added)).toEqual([
      'ALTER TABLE [dbo].[t] ADD [b] text;',
    ]);
    expect(buildAlterTable('cassandra', { database: 'k', name: 't' }, one, added)).toEqual([
      'ALTER TABLE "k"."t" ADD "b" text;',
    ]);
  });

  it('says what an engine cannot change in place', () => {
    const one = [{ name: 'a', type: 'int', nullable: true, primaryKey: false, defaultValue: '1' }];
    expect(() =>
      buildAlterTable('sqlite', { name: 't' }, one, [
        { ...one[0]!, originalName: 'a', type: 'text' },
      ]),
    ).toThrow(/SQLite cannot change/);
    expect(() =>
      buildAlterTable('cassandra', { name: 't' }, one, [
        { ...one[0]!, originalName: 'a', type: 'text' },
      ]),
    ).toThrow(/Cassandra cannot change/);
    expect(() =>
      buildAlterTable('mssql', { name: 't' }, one, [
        { ...one[0]!, originalName: 'a', defaultValue: '5' },
      ]),
    ).toThrow(/named constraints/);
    expect(() =>
      buildAlterTable('postgres', { name: 't' }, one, [
        { ...one[0]!, originalName: 'a', defaultValue: '1; drop' },
      ]),
    ).toThrow(/one value/);
  });

  it('answers nothing when nothing changed', () => {
    expect(
      buildAlterTable(
        'postgres',
        { name: 't' },
        before,
        before.map((column) => ({ ...column, originalName: column.name })),
      ),
    ).toEqual([]);
  });
});

describe('Mongo collections', () => {
  it('makes a plain collection when no fields are named', () => {
    expect(buildCreateTable('mongodb', { ref: { name: 'logs' }, columns: [] })).toBe(
      'db.createCollection("logs")',
    );
  });
});

describe('buildDropTable', () => {
  it('drops a table, or a Mongo collection', () => {
    expect(buildDropTable('postgres', { schema: 'public', name: 't' })).toBe(
      'DROP TABLE "public"."t";',
    );
    expect(buildDropTable('mongodb', { database: 'shop', name: 'a"b' })).toBe(
      'db.getCollection("a\\"b").drop()',
    );
  });
});

describe('sqlLiteral', () => {
  it('writes NULL, numbers and booleans bare where the column takes them', () => {
    expect(sqlLiteral('postgres', null, 'text')).toBe('NULL');
    expect(sqlLiteral('postgres', '42', 'integer')).toBe('42');
    expect(sqlLiteral('postgres', '4.5', 'numeric(10,2)')).toBe('4.5');
    expect(sqlLiteral('postgres', 'true', 'boolean')).toBe('TRUE');
    expect(sqlLiteral('cassandra', '7', 'int')).toBe('7');
    expect(sqlLiteral('mysql', 1, 'tinyint(1)')).toBe('1');
    expect(sqlLiteral('postgres', 'f', 'bool')).toBe('FALSE');
    expect(sqlLiteral('postgres', 'maybe', 'boolean')).toBe("'maybe'");
    expect(sqlLiteral('cassandra', '0f8fad5b-d9cb-469f-a165-70867728950e', 'uuid')).toBe(
      '0f8fad5b-d9cb-469f-a165-70867728950e',
    );
  });

  it('quotes everything else, and a number in a text column', () => {
    expect(sqlLiteral('postgres', '42', 'text')).toBe("'42'");
    expect(sqlLiteral('postgres', "O'Brien", 'text')).toBe("'O''Brien'");
    expect(sqlLiteral('postgres', '1; drop table t', 'integer')).toBe("'1; drop table t'");
    expect(sqlLiteral('mssql', 'é', 'nvarchar(10)')).toBe("N'é'");
    expect(sqlLiteral('postgres', { a: 1 }, 'jsonb')).toBe(`'{"a":1}'`);
  });
});

describe('buildRowEdits', () => {
  const columns = [
    { name: 'id', type: 'integer' },
    { name: 'name', type: 'text' },
  ];

  it('wraps updates, inserts and deletes in one transaction, keyed by the primary key', () => {
    expect(
      buildRowEdits('postgres', { schema: 'public', name: 't' }, columns, [
        { kind: 'update', key: { id: 1 }, values: { name: 'Ada' } },
        { kind: 'insert', values: { id: '3', name: null } },
        { kind: 'delete', key: { id: 2 } },
      ]),
    ).toBe(
      [
        'BEGIN;',
        `UPDATE "public"."t" SET "name" = 'Ada' WHERE "id" = 1;`,
        'INSERT INTO "public"."t" ("id", "name") VALUES (3, NULL);',
        'DELETE FROM "public"."t" WHERE "id" = 2;',
        'COMMIT;',
      ].join('\n'),
    );
  });

  it('uses each engine own way to start a transaction, and none on Cassandra', () => {
    const edit = [{ kind: 'delete' as const, key: { id: 2 } }];
    expect(buildRowEdits('mysql', { database: 'd', name: 't' }, columns, edit)).toMatch(
      /^START TRANSACTION;/,
    );
    expect(buildRowEdits('mssql', { schema: 'dbo', name: 't' }, columns, edit)).toMatch(
      /^BEGIN TRANSACTION;/,
    );
    expect(buildRowEdits('cassandra', { database: 'k', name: 't' }, columns, edit)).toBe(
      'DELETE FROM "k"."t" WHERE "id" = 2;',
    );
  });

  it('matches NULL keys with IS NULL', () => {
    expect(
      buildRowEdits('postgres', { name: 't' }, columns, [
        { kind: 'delete', key: { id: 1, name: null } },
      ]),
    ).toContain('WHERE "id" = 1 AND "name" IS NULL');
  });

  it('turns down an edit with no key, so it can never hit every row', () => {
    expect(() =>
      buildRowEdits('postgres', { name: 't' }, columns, [
        { kind: 'update', key: {}, values: { a: 1 } },
      ]),
    ).toThrow(/key/i);
    expect(buildRowEdits('postgres', { name: 't' }, columns, [])).toBe('');
  });
});

describe('columnTypeSuggestions', () => {
  it('suggests the common types of each engine', () => {
    expect(columnTypeSuggestions('postgres')).toContain('jsonb');
    expect(columnTypeSuggestions('mysql')).toContain('varchar(255)');
    expect(columnTypeSuggestions('mongodb')).toContain('objectId');
    expect(columnTypeSuggestions('cassandra')).toContain('uuid');
    expect(columnTypeSuggestions('redis')).toEqual([]);
  });
});
