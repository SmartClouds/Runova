#!/usr/bin/env node
// Writes the mobile apps' design tokens from the desktop's own theme, so the three stay one design.
//
//   node scripts/mobile-design.mjs           write the Kotlin and Swift files
//   node scripts/mobile-design.mjs --check   fail if they are not what would be written (CI)

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const VARIABLE = /--([\w-]+):\s*(\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)%\s+(\d+(?:\.\d+)?)%\s*;/g;
const BLOCK = /([^{}]+)\{([^{}]*)\}/g;
const HEADER = "Generated by scripts/mobile-design.mjs from the desktop's theme. Do not edit.";

/** The hex color for a CSS `H S% L%` triple, as uppercase `#RRGGBB`. */
export function hslToHex(triple) {
  const [h, s, l] = triple.split(/\s+/).map((part) => Number.parseFloat(part));
  const saturation = s / 100;
  const lightness = l / 100;
  const chroma = (1 - Math.abs(2 * lightness - 1)) * saturation;
  const segment = h / 60;
  const x = chroma * (1 - Math.abs((segment % 2) - 1));
  const [red, green, blue] = [
    [chroma, x, 0],
    [x, chroma, 0],
    [0, chroma, x],
    [0, x, chroma],
    [x, 0, chroma],
    [chroma, 0, x],
  ][Math.floor(segment) % 6] ?? [0, 0, 0];
  const match = lightness - chroma / 2;
  const channel = (value) =>
    Math.round((value + match) * 255)
      .toString(16)
      .padStart(2, '0');
  return `#${channel(red)}${channel(green)}${channel(blue)}`.toUpperCase();
}

/** The color variables of the block with exactly this selector. */
export function parseColorBlock(css, selector) {
  for (const [, selectors, body] of css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(BLOCK)) {
    if (!selectors.split(',').some((part) => part.trim() === selector)) continue;
    const colors = {};
    for (const [, name, h, s, l] of body.matchAll(VARIABLE)) {
      colors[name] = hslToHex(`${h} ${s}% ${l}%`);
    }
    return colors;
  }
  throw new Error(`No CSS block for ${selector}: the desktop's theme has moved.`);
}

export function parseRadius(css) {
  const match = /--radius:\s*([\d.]+)rem/.exec(css);
  if (!match) throw new Error('No --radius in the desktop theme.');
  return Math.round(Number.parseFloat(match[1]) * 16);
}

/** The six-digit colors of TERMINAL_THEME. Translucent ones and constants are skipped. */
export function parseTerminalTheme(source) {
  const block = /export const TERMINAL_THEME: ITheme = \{([\s\S]*?)\};/.exec(source);
  if (!block) throw new Error('No TERMINAL_THEME in the terminal factory.');
  const colors = {};
  for (const [, name, value] of block[1].matchAll(/(\w+):\s*'#([0-9a-fA-F]{6})'/g)) {
    colors[name] = `#${value.toUpperCase()}`;
  }
  return colors;
}

const camel = (name) => name.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());
const pascal = (name) => name[0].toUpperCase() + camel(name).slice(1);
const hex = (color) => color.slice(1);

function shared(tokens) {
  return Object.keys(tokens.light)
    .filter((name) => name in tokens.dark)
    .sort();
}

export function renderKotlin(tokens) {
  const names = shared(tokens);
  const terminal = Object.keys(tokens.terminal).sort();
  const fields = (list) => list.map((n) => `    val ${camel(n)}: Color,`).join('\n');
  const palette = (colors, list) =>
    list.map((n) => `        ${camel(n)} = Color(0xFF${hex(colors[n])}),`).join('\n');
  const icons = Object.entries(tokens.icons ?? {})
    .map(([name, code]) => `    const val ${pascal(name)} = "\\u${code}"`)
    .join('\n');
  return `// ${HEADER}
package com.runovahq.app.design

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

@Immutable
data class RunovaPalette(
${fields(names)}
)

@Immutable
data class RunovaTerminalPalette(
${fields(terminal)}
)

object RunovaTokens {
    const val RADIUS = ${tokens.radius}

    val Light = RunovaPalette(
${palette(tokens.light, names)}
    )

    val Dark = RunovaPalette(
${palette(tokens.dark, names)}
    )

    val Terminal = RunovaTerminalPalette(
${palette(tokens.terminal, terminal)}
    )
}

/** FontAwesome Solid code points, drawn with the bundled icon font. */
object RunovaIcons {
${icons}
}
`;
}

export function renderSwift(tokens) {
  const names = shared(tokens);
  const terminal = Object.keys(tokens.terminal).sort();
  const fields = (list) => list.map((n) => `    let ${camel(n)}: Color`).join('\n');
  const palette = (colors, list) =>
    list.map((n) => `        ${camel(n)}: Color(hex: 0x${hex(colors[n])})`).join(',\n');
  const icons = Object.entries(tokens.icons ?? {})
    .map(([name, code]) => `    static let ${camel(name)} = "\\u{${code}}"`)
    .join('\n');
  return `// ${HEADER}
import SwiftUI

extension Color {
    init(hex: UInt32) {
        self.init(
            .sRGB,
            red: Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue: Double(hex & 0xFF) / 255,
            opacity: 1
        )
    }
}

struct RunovaPalette {
${fields(names)}
}

struct RunovaTerminalPalette {
${fields(terminal)}
}

enum RunovaTokens {
    static let radius: CGFloat = ${tokens.radius}

    static let light = RunovaPalette(
${palette(tokens.light, names)}
    )

    static let dark = RunovaPalette(
${palette(tokens.dark, names)}
    )

    static let terminal = RunovaTerminalPalette(
${palette(tokens.terminal, terminal)}
    )
}

/// FontAwesome Solid code points, drawn with the bundled icon font.
enum RunovaIcons {
${icons}
}
`;
}

const ANSI_ORDER = [
  'black',
  'red',
  'green',
  'yellow',
  'blue',
  'magenta',
  'cyan',
  'white',
  'brightBlack',
  'brightRed',
  'brightGreen',
  'brightYellow',
  'brightBlue',
  'brightMagenta',
  'brightCyan',
  'brightWhite',
];

export function renderRust(tokens) {
  const missing = ANSI_ORDER.filter((name) => !(name in tokens.terminal));
  if (missing.length > 0) throw new Error(`The terminal theme has no ${missing.join(', ')}.`);
  const entries = ANSI_ORDER.map((name) => `    0x${hex(tokens.terminal[name])},`).join('\n');
  return `// ${HEADER}

#[rustfmt::skip]
pub const ANSI: [u32; 16] = [
${entries}
];

pub const FOREGROUND: u32 = 0x${hex(tokens.terminal.foreground)};
pub const BACKGROUND: u32 = 0x${hex(tokens.terminal.background)};
`;
}

