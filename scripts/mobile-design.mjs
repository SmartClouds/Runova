function collect(repo) {
  const desktop = join(repo, 'apps/desktop/src/renderer/src');
  const css = readFileSync(join(desktop, 'index.css'), 'utf8');
  const terminalSource = readFileSync(join(desktop, 'lib/terminal/xtermFactory.ts'), 'utf8');
  const well = /TERMINAL_WELL_BG\s*=\s*'#([0-9a-fA-F]{6})'/.exec(terminalSource);
  if (!well) throw new Error('No TERMINAL_WELL_BG in the terminal factory.');
  const solid = createRequire(join(repo, 'apps/desktop/package.json'))(
    '@fortawesome/free-solid-svg-icons',
  );
  const icons = {};
  for (const [name, exported] of Object.entries(ICONS)) {
    const icon = solid[exported];
    if (!icon) throw new Error(`FontAwesome has no ${exported}.`);
    icons[name] = icon.icon[3].toUpperCase().padStart(4, '0');
  }
  return {
    light: parseColorBlock(css, ':root'),
    dark: parseColorBlock(css, '.dark'),
    terminal: {
      ...parseTerminalTheme(terminalSource),
      background: `#${well[1].toUpperCase()}`,
    },
    radius: parseRadius(css),
    icons,
  };
}

function main() {
  const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const tokens = collect(repo);
  const outputs = [
    [
      'apps/mobile/android/app/src/main/kotlin/com/runovahq/app/design/Tokens.kt',
      renderKotlin(tokens),
    ],
    ['apps/mobile/ios/Runova/Design/Tokens.swift', renderSwift(tokens)],
    ['apps/mobile/core/crates/ffi/src/palette.rs', renderRust(tokens)],
    ['apps/mobile/design/icons.json', `${JSON.stringify(tokens.icons, null, 2)}\n`],
  ];
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [path, text] of outputs) {
    const target = join(repo, path);
    let current = null;
    try {
      current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      // Not written yet.
    }
    if (current === text) continue;
    if (check) stale.push(path);
    else writeFileSync(target, text);
  }
  if (stale.length > 0) {
    process.stderr.write(
      `Out of date with the desktop's theme: ${stale.join(', ')}\nRun: node scripts/mobile-design.mjs\n`,
    );
    process.exit(1);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
